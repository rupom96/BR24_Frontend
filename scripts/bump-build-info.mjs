/**
 * Bumps APP_VERSION (last segment +1) and refreshes APP_BUILD_STAMP
 * before each production build. Invoked via package.json `prebuild`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const target = path.resolve(
  __dirname,
  '../src/presentation/constants/buildInfo.ts'
);

const source = fs.readFileSync(target, 'utf8');
const versionMatch = source.match(
  /export const APP_VERSION = '([^']+)';/
);

if (!versionMatch) {
  console.error('bump-build-info: could not find APP_VERSION in', target);
  process.exit(1);
}

const parts = versionMatch[1].split('.').map((p) => {
  const n = Number(p);
  return Number.isFinite(n) ? n : 0;
});

if (parts.length === 0) {
  parts.push(0);
}

parts[parts.length - 1] += 1;
const nextVersion = parts.join('.');

const now = new Date();
const months = [
  'Jan',
  'Feb',
  'Mar',
  'Apr',
  'May',
  'Jun',
  'Jul',
  'Aug',
  'Sep',
  'Oct',
  'Nov',
  'Dec',
];

// Asia/Dhaka wall-clock parts (publish stamp for BR ops)
const dhaka = new Intl.DateTimeFormat('en-GB', {
  timeZone: 'Asia/Dhaka',
  day: 'numeric',
  month: 'numeric',
  year: 'numeric',
  hour: 'numeric',
  minute: '2-digit',
  hour12: true,
}).formatToParts(now);

const get = (type) => dhaka.find((p) => p.type === type)?.value ?? '';
const day = get('day');
const month = months[Number(get('month')) - 1] ?? get('month');
const year = get('year');
const hour = get('hour');
const minute = get('minute');
const dayPeriod = (get('dayPeriod') || '').toUpperCase();
const stamp = `${day} ${month}, ${year} | ${hour}:${minute} ${dayPeriod}`;

const next = `/** Auto-generated by \`scripts/bump-build-info.mjs\` on each \`npm run build\`. Do not edit by hand. */
export const APP_VERSION = '${nextVersion}';
export const APP_BUILD_STAMP = '${stamp}';
`;

fs.writeFileSync(target, next, 'utf8');
console.log(`build-info → Version ${nextVersion} · ${stamp}`);
